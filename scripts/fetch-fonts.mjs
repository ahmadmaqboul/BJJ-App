import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const css = readFileSync('/tmp/claude-0/-home-user/c592c4ec-e6ed-58d1-876d-4fa409ff9bc2/scratchpad/plex.css', 'utf8');

// Split into @font-face blocks, each preceded by a /* subset */ comment.
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
console.log(`found ${blocks.length} @font-face blocks`);

const KEEP = new Set(['arabic', 'latin', 'latin-ext']);
const out = [];
let downloaded = 0;

for (const [, subset, block] of blocks) {
  if (!KEEP.has(subset)) continue;
  const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
  const url = block.match(/url\((https:\/\/[^)]+)\)/)?.[1];
  if (!weight || !url) continue;

  const name = `ibm-plex-sans-arabic-${subset}-${weight}.woff2`;
  execFileSync('curl', ['-sS', '-m', '40', '-o', `public/fonts/${name}`, url]);
  downloaded += 1;

  out.push(
    block
      .replace(/url\(https:\/\/[^)]+\)/, `url('/fonts/${name}')`)
      .replace(/@font-face\s*\{/, '@font-face {')
      .trim(),
  );
}

const header = `/*
 * IBM Plex Sans Arabic — self-hosted.
 *
 * Served from the app's own origin rather than a CDN so the typeface is
 * precached by the service worker and the app renders correctly offline and on
 * a slow connection, which a gym in Nablus will have.
 *
 * SIL Open Font License 1.1 — https://github.com/IBM/plex
 * Generated by scripts/fetch-fonts.mjs; do not edit by hand.
 */
`;

writeFileSync('src/client/fonts.css', header + out.join('\n\n') + '\n');
console.log(`downloaded ${downloaded} font files`);
