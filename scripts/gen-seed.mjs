#!/usr/bin/env node
// Generates migrations/0002_seed.sql from scripts/sheet-import.json.
//
// Run: npm run db:seed
//
// Phone numbers are personal data. 0002_seed.sql is committed, so phones never
// go into it — they are written to scripts/phones.local.sql instead, which is
// gitignored and applied as a separate step (see README).
//
// Supply them in a gitignored scripts/phones.local.json:
//   { "علاء شريم": "0599123456", "نادر مشة": "0598765432" }
// Names must match name_ar exactly. Missing ones stay NULL and can be filled
// in from the admin UI instead.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const sheet = JSON.parse(readFileSync(join(here, 'sheet-import.json'), 'utf8'));
const phonesPath = join(here, 'phones.local.json');
const phones = existsSync(phonesPath)
  ? Object.fromEntries(
      // Keys starting with _ are notes about the file, not member names.
      Object.entries(JSON.parse(readFileSync(phonesPath, 'utf8'))).filter(
        ([k]) => !k.startsWith('_'),
      ),
    )
  : {};

const q = (v) =>
  v === null || v === undefined || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;
const n = (v) => (v === null || v === undefined ? 'NULL' : String(v));

/**
 * The sheet's monthly columns cover 2026 only; everything older is lumped into
 * the "سنة 2024" bucket. To know how many classes a member has done *since*
 * their last promotion we sum the monthly buckets from the promotion onward.
 * Classes run ~8/month on a fixed weekly schedule, so a promotion on or before
 * the 10th is treated as "that whole month counts", otherwise the count starts
 * the following month.
 */
function classesSincePromotion(m) {
  const [year, month, day] = m.last_promotion.split('-').map(Number);
  const firstMonth = year < 2026 ? 1 : day <= 10 ? month : month + 1;
  let sum = 0;
  for (const [k, v] of Object.entries(m.months ?? {})) {
    if (Number(k) >= firstMonth) sum += v;
  }
  return sum;
}

const lines = [];
const say = (s = '') => lines.push(s);

say('-- GENERATED by scripts/gen-seed.mjs — do not edit by hand.');
say(`-- Source: ${sheet._source}`);
say(`-- Sheet exported: ${sheet._exported_on}`);
say();

// ---------------------------------------------------------------- settings ---
say('--------------------------------------------------------------- settings ---');
const settings = {
  team_name: 'JUI-Jitsu',
  team_name_ar: 'نادي JUI-Jitsu — نابلس',
  default_currency: 'ILS',
  timezone: 'Asia/Hebron',
  // Sunday + Tuesday, matching "الحصة الأولى (أ)" / "الحصة الثانية (ث)".
  class_week_days: '0,2',
  default_class_type: 'gi',
  // How far ahead the promotion board flags someone as "coming up".
  promotion_lookahead_days: '60',
  imported_from_sheet_on: sheet._exported_on,
};
for (const [k, v] of Object.entries(settings)) {
  say(`INSERT INTO settings (key, value) VALUES (${q(k)}, ${q(v)});`);
}
say();

// --------------------------------------------------------- promotion rules ---
say('-------------------------------------------------------- promotion rules ---');
say('-- Seeded from what the team already practises: the sheet sets every');
say('-- "تاريخ الاستحقاق القادم" to exactly 6 months after the last promotion.');
say('-- The classes_* thresholds are the half the sheet was missing — they stop a');
say('-- member going up on elapsed time alone. ~8 classes/month means a full');
say('-- 6-month cycle is ~48 classes, so 40 is roughly 83% attendance.');
say('-- All of this is editable from Settings → Promotion rules.');
const rules = [
  // belt,    mo/stripe, cls/stripe, max, mo→belt, cls→belt, min_age, next
  ['white', 6, 40, 4, 6, 40, null, 'blue'],
  ['blue', 6, 40, 4, 6, 40, 16, 'purple'],
  ['purple', 6, 50, 4, 6, 50, 16, 'brown'],
  ['brown', 6, 50, 4, 6, 50, 18, 'black'],
  ['black', 12, 60, 4, 0, 0, 19, null],
];
for (const r of rules) {
  say(
    `INSERT INTO promotion_rules (belt, months_per_stripe, classes_per_stripe, max_stripes, ` +
      `months_to_next_belt, classes_to_next_belt, min_age, next_belt) VALUES (` +
      `${q(r[0])}, ${n(r[1])}, ${n(r[2])}, ${n(r[3])}, ${n(r[4])}, ${n(r[5])}, ${n(r[6])}, ${q(r[7])});`,
  );
}
say();

// ------------------------------------------------------------------- plans ---
say('------------------------------------------------------------------ plans ---');
say('-- PLACEHOLDER PRICES — set the real ones in Settings → Plans before use.');
say('-- Prices are in agorot (minor units): 15000 = 150.00 ₪.');
const plans = [
  ['اشتراك شهري', 'Monthly subscription', 'monthly', 15000, null, 30, 10],
  ['بطاقة ٨ حصص', '8-session card', 'package', 12000, 8, 90, 20],
  ['بطاقة ٤ حصص', '4-session card', 'package', 7000, 4, 60, 30],
  ['حصة واحدة', 'Single session', 'single', 2500, 1, 7, 40],
];
plans.forEach((p, i) => {
  say(
    `INSERT INTO plans (id, name_ar, name_en, type, price_minor, currency, sessions_included, validity_days, active, sort_order) ` +
      `VALUES (${i + 1}, ${q(p[0])}, ${q(p[1])}, ${q(p[2])}, ${n(p[3])}, 'ILS', ${n(p[4])}, ${n(p[5])}, 1, ${n(p[6])});`,
  );
});
say();

// ----------------------------------------------------------------- members ---
say('---------------------------------------------------------------- members ---');
let unmatchedPhones = new Set(Object.keys(phones));
const memberRows = [];

sheet.members.forEach((m, idx) => {
  const id = idx + 1;

  // Integrity check on the sheet itself: the two tabs must agree.
  const monthSum = Object.values(m.months ?? {}).reduce((a, b) => a + b, 0);
  const expected = (m.pre2026 ?? 0) + monthSum;
  if (expected !== m.total) {
    throw new Error(
      `Attendance mismatch for ${m.name_ar}: promotions tab says total ${m.total}, ` +
        `annual tab sums to ${expected} (pre2026 ${m.pre2026} + months ${monthSum}). ` +
        `Fix scripts/sheet-import.json before seeding.`,
    );
  }

  const since = classesSincePromotion(m);
  const atLastPromotion = m.total - since;
  if (atLastPromotion < 0) throw new Error(`Negative baseline for ${m.name_ar}`);

  unmatchedPhones.delete(m.name_ar);

  const notes = [];
  if (m.last_payment) notes.push(`آخر دفعة في الشيت: ${m.last_payment}`);
  if (m.owes_note) notes.push(m.owes_note);

  memberRows.push({ id, m, since, atLastPromotion });

  // phone is NULL here by design — see the note at the top of this file.
  say(
    `INSERT INTO members (id, name_ar, phone, join_date, status, belt, stripes, ` +
      `last_promotion_date, legacy_attendance, classes_at_last_promotion, notes) VALUES (` +
      `${id}, ${q(m.name_ar)}, NULL, ${q(m.join_date ?? m.last_promotion)}, ` +
      `${q(m.active ? 'active' : 'inactive')}, ${q(m.belt)}, ${n(m.stripes)}, ` +
      `${q(m.last_promotion)}, ${n(m.total)}, ${n(atLastPromotion)}, ` +
      `${q(notes.join(' · ') || null)});`,
  );
});
say();

// ------------------------------------------- legacy monthly attendance rows ---
say('------------------------------------------ legacy monthly attendance ---');
say('-- Kept so a member\'s history shows real past months instead of starting');
say('-- empty. year 0 / month 0 is the sheet\'s pre-2026 catch-all column.');
for (const { id, m } of memberRows) {
  if (m.pre2026) {
    say(
      `INSERT INTO legacy_monthly_attendance (member_id, year, month, classes) VALUES (${id}, 0, 0, ${n(m.pre2026)});`,
    );
  }
  for (const [month, classes] of Object.entries(m.months ?? {})) {
    if (!classes) continue;
    say(
      `INSERT INTO legacy_monthly_attendance (member_id, year, month, classes) VALUES (${id}, 2026, ${n(month)}, ${n(classes)});`,
    );
  }
}
say();

// -------------------------------------------------------- belt history seed ---
say('--------------------------------------------------------- belt history ---');
say('-- One "initial" row per member so belt history is populated from day one.');
say('-- Real promotions recorded in the app append to this instead of');
say('-- overwriting a cell, which is what the spreadsheet had to do.');
for (const { id, m, atLastPromotion } of memberRows) {
  say(
    `INSERT INTO promotions (member_id, to_belt, to_stripes, kind, promoted_on, ` +
      `classes_at_promotion, note) VALUES (${id}, ${q(m.belt)}, ${n(m.stripes)}, 'initial', ` +
      `${q(m.last_promotion)}, ${n(atLastPromotion)}, 'مستورد من شيت الترقيات');`,
  );
}
say();

// ------------------------------------------------------- opening balances ----
const owing = memberRows.filter(({ m }) => m.owes_minor);
if (owing.length) {
  say('------------------------------------------------------- opening balances ---');
  say('-- Free-text balance notes from the sheet, turned into real money owed.');
  for (const { id, m } of owing) {
    say(
      `INSERT INTO purchases (member_id, plan_id, plan_name_ar, plan_type, amount_minor, ` +
        `currency, sessions_total, sessions_used, valid_from, valid_until, status, note) VALUES (` +
        `${id}, NULL, 'رصيد سابق', 'opening_balance', ${n(m.owes_minor)}, 'ILS', 0, 0, ` +
        `${q(sheet._exported_on)}, NULL, 'active', ${q(m.owes_note)});`,
    );
  }
  say();
}

// ------------------------------------------------------------------ report ---
const out = join(root, 'migrations', '0002_seed.sql');
writeFileSync(out, lines.join('\n') + '\n');

const active = sheet.members.filter((m) => m.active).length;
const withPhone = sheet.members.filter((m) => phones[m.name_ar]).length;

// Phones go to their own gitignored file, applied separately, so no personal
// data is ever committed in a migration.
const phoneSqlPath = join(here, 'phones.local.sql');
if (withPhone) {
  const phoneLines = [
    '-- GENERATED from scripts/phones.local.json — contains personal data.',
    '-- GITIGNORED. Never commit this file.',
    '-- Apply with:',
    '--   npx wrangler d1 execute jui-jitsu-db --local  --file scripts/phones.local.sql',
    '--   npx wrangler d1 execute jui-jitsu-db --remote --file scripts/phones.local.sql',
    '',
  ];
  for (const { id, m } of memberRows) {
    const phone = phones[m.name_ar];
    if (!phone) continue;
    phoneLines.push(`UPDATE members SET phone = ${q(phone)} WHERE id = ${id};`);
  }
  writeFileSync(phoneSqlPath, phoneLines.join('\n') + '\n');
}

console.log(`Wrote ${out}`);
if (withPhone) console.log(`Wrote ${phoneSqlPath} (gitignored — apply separately)`);
console.log(`  members ............ ${sheet.members.length} (${active} active, ${sheet.members.length - active} inactive)`);
console.log(`  phones attached ..... ${withPhone}/${sheet.members.length}${withPhone === 0 ? '  (none — add scripts/phones.local.json or fill them in the admin UI)' : ''}`);
console.log(`  opening balances .... ${owing.length}`);
console.log(`  attendance totals ... all ${sheet.members.length} reconciled across both sheet tabs`);
if (unmatchedPhones.size) {
  console.warn(`\n  ⚠ phones.local.json has names not in the sheet: ${[...unmatchedPhones].join(', ')}`);
}
